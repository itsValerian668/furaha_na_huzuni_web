export const availableCredit = 850_000

export function getMemberLoans(memberId: string): Loan[] {
  return loans.filter((loan) => loan.memberId === memberId)
}

export function getActiveLoan(memberId: string): Loan | undefined {
  return loans.find(
    (loan) =>
      loan.memberId === memberId &&
      (loan.status === 'ACTIVE' || loan.status === 'OVERDUE'),
  )
}

export function getLoanById(id: string): Loan | undefined {
  return loans.find((loan) => loan.id === id)
}
